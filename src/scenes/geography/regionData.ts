/** 未收录区域的通用资料卡（按大洲模板生成，保证任何选择都有内容）。 */
export function cardFor(f: RegionFeature): RegionCard {
  const c = BUILTIN_CARDS[f.properties.NAME];
  if (c) return c;
  const continent = f.properties.CONTINENT ?? '该大洲';
  const sub = f.properties.SUBREGION ?? '';
  return {
    区位: `位于${continent}${sub ? '的' + sub : ''}，可通过旋转地球观察它与海陆、邻国的相对位置。`,
    地形地貌: `${continent}区域，地形与气候的详细资料可通过"AI 讲解"获取（需联网配置 DeepSeek）。`,
    人文特征: `人口约 ${f.properties.POP_EST ? Math.round(f.properties.POP_EST / 10000) / 100 + ' 千万' : '未知'}，更多信息可用"AI 讲解"获取。`,
  };
}

