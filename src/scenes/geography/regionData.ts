/** 区域数据：离线 GeoJSON 边界 + 内置资料卡 + 任务 A 线索库。
 *  有网时可用 DeepSeek 增强（见 llm.ts），离线时以下内容即完整保底。
 */
let cache: Promise<RegionFeature[]> | null = null;
export function loadWorld(): Promise<RegionFeature[]> {
  cache ??= fetch('/assets/world-110m.geojson')
    .then(r => r.json())
    .then((d: { features: RegionFeature[] }) => d.features);
  return cache;
}

